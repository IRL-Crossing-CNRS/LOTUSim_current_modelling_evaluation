#!/usr/bin/env python3
"""Generate one BlueROV2_current_fitted_ekman_<date>.yml per Copernicus day.

Unlike Gauss-Markov/Copernicus, xdyn's `ekman current` parameters live in the
vehicle YAML itself (`environment models: - model: ekman current`), not in
the scenario JSON -- scenario_launch.sh selects
`assets/models/bluerov2_heavy/BlueROV2_current_${bluerov_current}.yml`
straight off the scenario's `bluerov_current` string (no lookup table, see
that script). So a per-day fitted Ekman condition needs a per-day vehicle
YAML: this substitutes `current velocity`, `current orientation`, `top layer
thickness`, `bottom layer thickness` and `U10` from fit_ekman_profile.py's
output into a copy of the base BlueROV2_current_ekman.yml, leaving the
vehicle model, thrusters, wind orientation, latitude and seabed depth
untouched.

No new `.world` file is needed: `world_file` only selects the Gazebo/Unity
scene, not the current model (confirmed against scenario_launch.sh), and
every existing scenario already points at the one shared `bluerov_ekman.world`
regardless of `bluerov_current`.

Run from the repository root, after fit_ekman_profile.py:

    python3 src/simulation_run/scripts/bluerov_current_experiment/generate_fitted_ekman_assets.py
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re

FITTED_PARAMS_DIR = "src/simulation_run/config/bluerov_current_experiment/fitted_params_deep"
BASE_YAML = "assets/models/bluerov2_heavy/BlueROV2_current_ekman.yml"
LOTUSIM_PATH_DEFAULT = os.environ.get("LOTUSIM_PATH")

REPLACEMENTS = {
    "current velocity": ("current_velocity_ms", "m/s"),
    "current orientation": ("current_orientation_deg", "deg"),
    "top layer thickness": ("top_layer_thickness_m", "m"),
    "bottom layer thickness": ("bottom_layer_thickness_m", "m"),
    "U10": ("U10_ms", "m/s"),
}

HEADER_NOTE = """\
# GENERATED by generate_fitted_ekman_assets.py from {base} -- do not edit by
# hand, edit fit_ekman_profile.py's model port or its output instead.
#
# Ekman parameters below are fit to the {date} Copernicus depth profile via
# a direct port of xdyn's compiled `ekman current` model (see
# fit_ekman_profile.py, ekman_xdyn_model()). Fit RMSE against the measured
# profile: {rmse:.5f} m/s.
#
"""


def substitute(yaml_text: str, fitted: dict) -> str:
    out = yaml_text
    for key_prefix, (json_key, unit) in REPLACEMENTS.items():
        value = fitted[json_key]
        pattern = re.compile(
            rf"^(\s*{re.escape(key_prefix)}:\s*\{{\s*value:\s*)[-\d.eE]+(\s*,\s*unit:\s*{re.escape(unit)}\s*\}}\s*)$",
            re.MULTILINE,
        )
        new_out, n = pattern.subn(rf"\g<1>{value}\g<2>", out)
        if n != 1:
            raise SystemExit(
                f"expected exactly one '{key_prefix}' line matching unit "
                f"'{unit}' in the base YAML, found {n}"
            )
        out = new_out
    return out


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--lotusim-path",
        default=LOTUSIM_PATH_DEFAULT,
        help="path to the LOTUSim workspace holding assets/ "
        "(default: $LOTUSIM_PATH)",
    )
    ap.add_argument("--fitted-params-dir", default=FITTED_PARAMS_DIR)
    args = ap.parse_args()

    if not args.lotusim_path:
        raise SystemExit(
            "no LOTUSim workspace path given -- pass --lotusim-path or set "
            "$LOTUSIM_PATH"
        )

    base_path = os.path.join(args.lotusim_path, BASE_YAML)
    if not os.path.exists(base_path):
        raise SystemExit(f"base vehicle YAML not found: {base_path}")
    with open(base_path) as f:
        base_text = f.read()

    param_files = sorted(
        glob.glob(os.path.join(args.fitted_params_dir, "ekman_*.json"))
    )
    if not param_files:
        raise SystemExit(
            f"no fitted params in {args.fitted_params_dir} -- run "
            f"fit_ekman_profile.py first."
        )

    for pf in param_files:
        with open(pf) as f:
            data = json.load(f)
        date = data["date"]
        fitted = data["fitted"]
        rmse = data["fit_rmse_ms"]

        out_text = substitute(base_text, fitted)
        header = HEADER_NOTE.format(base=BASE_YAML, date=date, rmse=rmse)
        out_text = header + out_text

        out_name = f"BlueROV2_current_fitted_ekman_{date}.yml"
        out_path = os.path.join(args.lotusim_path, os.path.dirname(BASE_YAML), out_name)
        with open(out_path, "w") as f:
            f.write(out_text)
        print(f"{date}: wrote {out_path}")


if __name__ == "__main__":
    main()
