#!/usr/bin/env python3
"""Scenarios for the model-as-ENVIRONMENT comparison.

This is not the feedforward experiment. There, the applied current was always
the measured Copernicus profile and only the *controller's belief* changed -- a
harder question, and one whose answer turned out to be structurally negative:
the depth-uniform model's error is ~93% a constant bias, which a PID's integral
action removes for free, leaving a depth-resolved model almost nothing to add.

Here the current model IS the environment: comparing simulations that use a
standard environmental model against ones that use the Ekman-based model
establishes whether, and how, the choice alters system-level behaviour. The
vehicle and controller are held identical and only `bluerov_current` changes:

  * `copernicus`          -- the measured profile: ground truth
  * `gauss`               -- Gauss-Markov, what UUVSim and DAVE provide
  * `fitted_ekman_<date>` -- the fitted-Ekman model, fitted to that day's profile

There is no feedforward in any condition: the controller is plain PID and knows
nothing about the current. Any difference in trajectory, tracking or energy is
therefore caused by the simulated environment alone, which is the quantity a
roboticist inherits when they choose a simulator.

The useful reading is against `copernicus`: whichever model's predicted
behaviour lands closer to the measured-profile run is the model that would have
told a developer the truth about their vehicle.

Four transects, matching this study's transect design exactly:
Level (25 m, no vertical crossing, a control), Sweep A/B/C (10-40, 45-75,
80-110 m -- a depth sinusoid centred on each, amplitude 15 m) so together
they cross the wind-driven layer, the geostrophic layer, or both depending
on the date's fit. Reconstructed on 2026-08-27 to match the already-published
26 dates' scenario files exactly (this script's previous BANDS/geometry
defaults -- "upper"/"lower", amplitude-only sinusoids, ground_track=90 --
produced a different, unused scenario shape; verified by diffing this
script's output against every field of an existing published scenario JSON
for the same date).
"""
from __future__ import annotations

import argparse
import json
import math
import os

CONFIG_DIR = "src/simulation_run/config/bluerov_current_experiment"
PROFILE_SUBDIR = "copernicus_profiles_deep"


def waypoints(depth: float, amp: float, wl: float, track: float, spacing: float) -> list:
    n = int(round(track / spacing))
    return [[round((i + 1) * spacing, 4), 0.0,
             round(depth + amp * math.sin(2 * math.pi * (i + 1) * spacing / wl), 4)]
            for i in range(n)]


def current_source(current: str, date: str, gm: dict) -> dict:
    """The single ROS2-side current block for this condition, if any."""
    if current == "copernicus":
        return {"copernicus_current": {"profile": f"{PROFILE_SUBDIR}/brest_{date}.csv"}}
    if current == "gauss":
        return {"gauss_markov_current": {
            "mean_x": gm["mean_x"], "mean_y": gm["mean_y"],
            "tau": 60.0, "std_dev": gm["std_dev"], "seed": 1}}
    # fitted_ekman_<date>: xdyn computes the field itself from the vehicle YAML,
    # so nothing must be injected from ROS2.
    return {}


def build(date, band, depth, amplitude, current, args, gm) -> dict:
    run = f"env_{band}_{current_tag(current)}_{date}"
    return {
        "_comment": [
            "Model-as-environment comparison, generated by "
            "generate_environment_experiment.py.",
            f"Applied current: {current}. Controller: plain PID, no feedforward, "
            "identical in every condition -- so any difference comes from the "
            "simulated environment alone.",
            f"Depth band centred {depth} m, amplitude {amplitude} m, "
            f"u0={args.u0} m/s, lambda={args.wavelength} m.",
        ],
        "world_file": "bluerov_ekman.world",
        "bluerov_current": current,
        "agents": [{
            "id": f"bluerov_env_{band}", "class": "Bluerov2_heavy_current",
            "nb_agents": 1, "xdyn": True,
            "spawn": {"x": 0.0, "y": 0.0, "z": -depth, "yaw": 0.0},
            "tick_rate_hz": 1.0,
            "missions": [
                {"id": "navigation", "type": "action",
                 "task": "bluerov_navigation", "params": {}},
                {"id": "path", "type": "action",
                 "task": "bluerov_guidance_los_polyline",
                 "params": {"waypoints": waypoints(depth, amplitude,
                                                   args.wavelength, args.ground_track,
                                                   args.spacing),
                            "z_start_m": depth, "u_setpoint_ms": args.u0,
                            "lookahead_m": args.lookahead}},
                # No feedforward block at all: this experiment is about the
                # environment, not about what the controller believes.
                {"id": "control", "type": "action",
                 "task": "bluerov_control", "params": {}},
                {"id": "allocation", "type": "action",
                 "task": "bluerov_allocation", "params": {}},
                {"id": "metrics", "type": "action",
                 "task": "bluerov_metrics_recorder",
                 "params": {"output_dir": f"results/{args.results_subdir}",
                            "run_name": run, "settle_s": 15.0}},
            ],
            # Exactly ONE current source per condition. The three are injected by
            # different mechanisms and they compose silently if more than one is
            # present, which is a trap: `ekman current` lives inside the xdyn YAML
            # selected by `bluerov_current`, while `copernicus`/`gauss` carry no
            # xdyn current model at all and are injected from ROS2 through these
            # keys. Leaving `copernicus_current` in place for the Ekman condition
            # therefore replays the measured profile ON TOP OF the Ekman field.
            **current_source(current, date, gm),
        }],
        "aerial_domain": False, "renderer_unity": True,
    }


def current_tag(current: str) -> str:
    return "ekman" if current.startswith("fitted_ekman") else current


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config-dir", default=CONFIG_DIR)
    ap.add_argument("--dates", nargs="+", required=True)
    ap.add_argument(
        "--bands", default="flat=25:0,shallow=25:15,mid=60:15,deep=95:15",
        help="band=depth:amplitude,... . Default reproduces this study's "
             "Level (25 m, no crossing), Sweep A (10-40 m), B (45-75 m) and "
             "C (80-110 m).")
    ap.add_argument("--u0", type=float, default=0.15)
    ap.add_argument("--wavelength", type=float, default=45.0)
    ap.add_argument("--ground-track", type=float, default=60.0)
    ap.add_argument("--spacing", type=float, default=1.5)
    ap.add_argument("--lookahead", type=float, default=3.0)
    ap.add_argument("--results-subdir", default="bluerov_environment_experiment")
    args = ap.parse_args()

    bands = {}
    for kv in args.bands.split(","):
        band, rest = kv.split("=")
        depth, amplitude = (float(v) for v in rest.split(":"))
        bands[band] = (depth, amplitude)

    n = 0
    for date in args.dates:
        gm_path = os.path.join(args.config_dir, "fitted_params_deep", f"gauss_{date}.json")
        with open(gm_path) as f:
            gm = json.load(f)["fitted"]
        for band, (depth, amplitude) in bands.items():
            for current in ("copernicus", "gauss", f"fitted_ekman_{date}"):
                out = build(date, band, depth, amplitude, current, args, gm)
                name = f"env_{band}_{current_tag(current)}_{date}.json"
                with open(os.path.join(args.config_dir, name), "w") as f:
                    json.dump(out, f, indent=2)
                    f.write("\n")
                n += 1
        print(f"  {date}: {len(bands) * 3} scenario(s)")
    print(f"\n{n} scenario(s) written to {args.config_dir}")


if __name__ == "__main__":
    main()
